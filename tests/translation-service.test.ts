import { describe, expect, it, vi } from 'vitest';
import { AppError } from '@/lib/messages';
import { createTranslationService } from '@/lib/translation-service';
import { deferred, makeKey, makeMemory, makeSource, settings, identity } from './history-fixtures';

describe('memory-first generation and regeneration', () => {
  it('saves once, then reuses across channels and missing credentials without network calls', async () => {
    const { memory } = makeMemory();
    const translate = vi.fn(async () => '你好');
    const service = createTranslationService(memory, translate);
    const first = await service(settings, identity.sourceText, makeSource());
    expect(first).toMatchObject({ origin: 'model', persistence: { status: 'saved' } });
    expect(await service({ ...settings, apiKey: '', revision: 'new' }, identity.sourceText, makeSource('21'))).toMatchObject({ origin: 'memory', translatedText: '你好' });
    expect(translate).toHaveBeenCalledOnce();
    expect((await memory.get(first.entryId)).sources).toHaveLength(2);
    await expect(service({ ...settings, apiKey: '' }, 'no record', makeSource())).rejects.toMatchObject({ detail: { kind: 'missing_configuration' } });
    await memory.close();
  });
  it('holds the shared job through persistence, not just until the model resolves', async () => {
    const { memory } = makeMemory();
    const gate = deferred<void>();
    const save = memory.save.bind(memory);
    const saving = vi.spyOn(memory, 'save').mockImplementation(async (...args) => { await gate.promise; return save(...args); });
    const translate = vi.fn(async () => 'shared');
    const service = createTranslationService(memory, translate);
    const first = service(settings, 'A', makeSource());
    await vi.waitFor(() => expect(saving).toHaveBeenCalledOnce());
    const second = service(settings, 'A', makeSource('21'));
    await vi.waitFor(() => expect(translate).toHaveBeenCalledOnce());
    gate.resolve();
    const [a, b] = await Promise.all([first, second]);
    expect(a.translatedText).toBe(b.translatedText);
    expect(translate).toHaveBeenCalledOnce();
    expect((await memory.get(a.entryId)).sources).toHaveLength(2);
    await memory.close();
  });
  it('rechecks a stale miss after the previous job has committed and left the map', async () => {
    const { memory } = makeMemory();
    const gate = deferred<void>();
    const inspected = deferred<void>();
    const inspect = memory.inspect.bind(memory);
    vi.spyOn(memory, 'inspect').mockImplementationOnce(async key => { const result = await inspect(key); inspected.resolve(); await gate.promise; return result; });
    const translate = vi.fn(async () => 'one');
    const service = createTranslationService(memory, translate);
    const slow = service(settings, 'A', makeSource());
    await inspected.promise;
    await service(settings, 'A', makeSource('21'));
    gate.resolve(); await slow;
    expect(translate).toHaveBeenCalledOnce();
    await memory.close();
  });
  it('reports read failure without calling the provider and reports write failure with the real text', async () => {
    const { memory } = makeMemory();
    const translate = vi.fn(async () => '真实译文');
    const service = createTranslationService(memory, translate);
    vi.spyOn(memory, 'inspect').mockRejectedValueOnce(new AppError({ kind: 'history_read', message: 'read failed' }));
    await expect(service(settings, 'A', makeSource())).rejects.toThrow('read failed');
    expect(translate).not.toHaveBeenCalled();
    vi.spyOn(memory, 'save').mockRejectedValueOnce(new DOMException('Full', 'QuotaExceededError'));
    expect(await service(settings, 'A', makeSource())).toMatchObject({ translatedText: '真实译文', persistence: { status: 'not-saved', error: { kind: 'history_write', storageCode: 'QuotaExceededError' } } });
    expect(translate).toHaveBeenCalledOnce();
    expect((await memory.list({})).items).toHaveLength(0);
    await memory.close();
  });
  it('retains a cached result when source association fails, without fetching', async () => {
    const { memory } = makeMemory();
    const translate = vi.fn(async () => 'cached');
    const service = createTranslationService(memory, translate);
    await service(settings, 'A', makeSource());
    vi.spyOn(memory, 'associate').mockRejectedValueOnce(new Error('write failed'));
    expect(await service(settings, 'A', makeSource('21'))).toMatchObject({ origin: 'memory', translatedText: 'cached', persistence: { status: 'not-saved' } });
    expect(translate).toHaveBeenCalledOnce();
    await memory.close();
  });
  it('coalesces regeneration while ordinary readers keep the committed old text', async () => {
    const { memory } = makeMemory();
    const gate = deferred<string>();
    const translate = vi.fn().mockResolvedValueOnce('old').mockImplementationOnce(() => gate.promise);
    const service = createTranslationService(memory, translate);
    const old = await service(settings, 'A', makeSource());
    const before = (await memory.get(old.entryId)).entry;
    const refresh = service(settings, 'A', makeSource(), true);
    await vi.waitFor(() => expect(translate).toHaveBeenCalledTimes(2));
    const duplicate = service(settings, 'A', makeSource('21'), true);
    expect((await service(settings, 'A', makeSource('22'))).translatedText).toBe('old');
    gate.resolve('new'); await Promise.all([refresh, duplicate]);
    expect(translate).toHaveBeenCalledTimes(2);
    expect((await service(settings, 'A', makeSource())).translatedText).toBe('new');
    expect((await memory.get(old.entryId)).entry).toMatchObject({ createdAt: before.createdAt, createdSequence: before.createdSequence, translatedText: 'new' });
    await memory.close();
  });
  it('queues one explicit regeneration after an earlier ordinary generation', async () => {
    const { memory } = makeMemory();
    const firstOutput = deferred<string>();
    const translate = vi.fn().mockImplementationOnce(() => firstOutput.promise).mockResolvedValueOnce('fresh');
    const service = createTranslationService(memory, translate);
    const ordinary = service(settings, 'A', makeSource());
    await vi.waitFor(() => expect(translate).toHaveBeenCalledOnce());
    const inspected = vi.spyOn(memory, 'inspect');
    const refresh = service(settings, 'A', makeSource('21'), true);
    const duplicate = service(settings, 'A', makeSource('22'), true);
    await vi.waitFor(() => expect(inspected).toHaveResolvedTimes(2));
    firstOutput.resolve('old');
    await Promise.all([ordinary, refresh, duplicate]);
    expect(translate).toHaveBeenCalledTimes(2);
    expect((await service(settings, 'A', makeSource())).translatedText).toBe('fresh');
    await memory.close();
  });
  it('keeps old records on provider or replacement failure, with an inspectable unsaved candidate', async () => {
    const { memory } = makeMemory();
    const translate = vi.fn().mockResolvedValueOnce('old').mockRejectedValueOnce(new AppError({ kind: 'payment', message: 'no credit' })).mockResolvedValueOnce('candidate');
    const service = createTranslationService(memory, translate);
    const first = await service(settings, 'A', makeSource());
    await expect(service(settings, 'A', makeSource(), true)).rejects.toThrow('no credit');
    vi.spyOn(memory, 'save').mockRejectedValueOnce(new Error('commit failed'));
    expect(await service(settings, 'A', makeSource(), true)).toMatchObject({ translatedText: 'candidate', persistence: { status: 'not-saved' } });
    expect((await memory.get(first.entryId)).entry.translatedText).toBe('old');
    await expect(service({ ...settings, apiKey: '' }, 'A', makeSource(), true)).rejects.toMatchObject({ detail: { kind: 'missing_configuration' } });
    await memory.close();
  });
  it('blocks delayed writes and queued regeneration after a clear', async () => {
    const { memory } = makeMemory();
    const output = deferred<string>();
    const translate = vi.fn(() => output.promise);
    const service = createTranslationService(memory, translate);
    const normal = service(settings, 'A', makeSource());
    await vi.waitFor(() => expect(translate).toHaveBeenCalledOnce());
    const inspected = vi.spyOn(memory, 'inspect');
    const queued = service(settings, 'A', makeSource('21'), true);
    const rejection = expect(queued).rejects.toMatchObject({ detail: { kind: 'history_deleted' } });
    await vi.waitFor(() => expect(inspected).toHaveResolved());
    await memory.clear(); output.resolve('late');
    expect(await normal).toMatchObject({ persistence: { status: 'not-saved', error: { kind: 'history_deleted' } } });
    await rejection;
    expect(translate).toHaveBeenCalledOnce();
    expect((await memory.list({})).items).toHaveLength(0);
    await memory.close();
  });
  it('does not store invalid model output or automatically retry a shared failure', async () => {
    const { memory } = makeMemory();
    const translate = vi.fn(async () => '');
    const service = createTranslationService(memory, translate);
    await expect(service(settings, 'A', makeSource())).rejects.toMatchObject({ detail: { kind: 'response' } });
    expect((await memory.inspect(await makeKey({ sourceText: 'A' }))).entry).toBeUndefined();
    expect(translate).toHaveBeenCalledOnce();
    await memory.close();
  });
  it('shares an active regeneration with an ordinary miss and shares real provider errors', async () => {
    const { memory } = makeMemory();
    const gate = deferred<string>();
    const translate = vi.fn(() => gate.promise);
    const service = createTranslationService(memory, translate);
    const refreshing = service(settings, 'not saved yet', makeSource(), true);
    const results = [refreshing];
    const settled = Promise.allSettled(results);
    await vi.waitFor(() => expect(translate).toHaveBeenCalledOnce());
    const inspected = vi.spyOn(memory, 'inspect');
    const ordinary = service(settings, 'not saved yet', makeSource('21'));
    const ordinaryResult = Promise.allSettled([ordinary]);
    await vi.waitFor(() => expect(inspected).toHaveResolved());
    gate.reject(new AppError({ kind: 'payment', message: 'no credit' }));
    expect((await settled)[0]).toMatchObject({ status: 'rejected', reason: { detail: { kind: 'payment' } } });
    expect((await ordinaryResult)[0]).toMatchObject({ status: 'rejected', reason: { detail: { kind: 'payment' } } });
    expect(translate).toHaveBeenCalledOnce();
    expect((await memory.list({})).items).toHaveLength(0);
    await memory.close();
  });
});
